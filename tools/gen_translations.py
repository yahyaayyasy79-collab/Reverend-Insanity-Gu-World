#!/usr/bin/env python3
"""Generate the mod's translation files (MOD_SPEC section 11; docs/Translating/Translation-mods.md).

  jsons/translations/Indonesian.properties   every string the mod shows (names, cities, leaders, event texts and
                                             choices, ruin notifications) from data/translations_id.csv, the
                                             civilopedia from data/civilopedia.csv, and the primeval-stones rename
  jsons/translations/English.properties      the primeval-stones rename only

The rename ("Gold" is displayed as primeval stones, the user's choice: "Batu Primordial" in Indonesian) overrides
every base-game translation key that contains the word Gold (not Golden, not inside [placeholders]); the base
translations are read from the release jar (ref/Unciv-<tag>.jar, tools/fetch_ref.sh). Keys and placeholders follow
the base files exactly: "English text = translation", one per line.

The in-game "Generate translation files" tool needs desktop; the user plays on Android, so this script does its job.

Usage: tools/gen_translations.py [--check] [--quiet]
"""
from __future__ import annotations

import argparse
import csv
import re
import sys
import zipfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from common import REF_DIR, REPO_ROOT, ref_tag  # noqa: E402

DATA = REPO_ROOT / "data"
OUT = REPO_ROOT / "jsons" / "translations"
STONES_EN, STONES_ID = "Primeval Stones", "Batu Primordial"
SKIP = ("Gold Ore", "Seven Cities of Gold")  # Vanilla objects this ruleset does not have
PLACEHOLDER = re.compile(r"(\[[^\]]*\])")


def table(name: str) -> list[dict]:
    with open(DATA / name, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def base_translations(language: str) -> dict[str, str]:
    jar = REF_DIR / f"Unciv-{ref_tag()}.jar"
    with zipfile.ZipFile(jar) as z:
        text = z.read(f"jsons/translations/{language}.properties").decode("utf-8")
    out = {}
    for line in text.splitlines():
        if " = " in line and not line.startswith("#"):
            k, v = line.split(" = ", 1)
            out[k] = v
    return out


def outside_brackets(text: str, fn) -> str:
    """Apply fn to the parts of text that are not [placeholders]."""
    return "".join(part if PLACEHOLDER.fullmatch(part) else fn(part) for part in PLACEHOLDER.split(text))


def stones_overrides(base_id: dict[str, str]) -> tuple[list[tuple[str, str]], list[tuple[str, str]]]:
    en, idn = [], []
    for key in sorted(base_id):
        if any(s in key for s in SKIP) or "\\n" in key:
            continue
        if not re.search(r"\bGold\b", PLACEHOLDER.sub("", key)):
            continue
        en.append((key, outside_brackets(key, lambda s: re.sub(r"\bGold\b", STONES_EN, s))))
        idn.append((key, outside_brackets(base_id[key], lambda s: re.sub(r"\bemas\b", STONES_ID.lower(),
                                                                      re.sub(r"\bEmas\b", STONES_ID, s)))))
    return en, idn


def displayed_strings(mod_root: Path = REPO_ROOT) -> list[str]:
    """Every string of the mod that Unciv shows and translates: object names, leaders, cities, event texts and
    choices, ruin notifications (uniques are translated through the base templates plus these names)."""
    import json
    jsons = Path(mod_root) / "jsons"
    load = lambda f: json.loads((jsons / f).read_text(encoding="utf-8"))  # noqa: E731
    out: list[str] = []
    out += [e["name"] for e in load("Eras.json")]
    out += [t["name"] for c in load("Techs.json") for t in c["techs"]]
    for f in ("Units.json", "UnitPromotions.json", "Buildings.json", "TileResources.json", "UnitTypes.json",
              "CityStateTypes.json", "VictoryTypes.json"):
        out += [o["name"] for o in load(f)]
    out += [p["name"] for b in load("Policies.json") for p in [b] + b["policies"]]
    out += [i["name"] for i in load("TileImprovements.json") if "techRequired" in i or "Unbuildable" in i.get("uniques", [])]
    for n in load("Nations.json"):
        if n["name"] != "Spectator":
            out += [n["name"]] + ([n["leaderName"]] if n.get("leaderName") else []) + n.get("cities", [])
    for e in load("Events.json"):
        out += ([e["text"]] if e.get("text") else []) + [c["text"] for c in e["choices"]]
    for r in load("Ruins.json"):
        out += [r["name"], r["notification"]]
    return list(dict.fromkeys(out))


def read_properties(path: Path) -> dict[str, str]:
    out = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if " = " in line and not line.startswith("#"):
            k, v = line.split(" = ", 1)
            out[k] = v
    return out


def render(sections: list[tuple[str, list[tuple[str, str]]]]) -> str:
    lines = ["# Generated by tools/gen_translations.py from data/*.csv - edit the tables, not this file.", ""]
    seen = set()
    for title, pairs in sections:
        lines.append(f"# {title}")
        for k, v in pairs:
            if k in seen:
                continue
            seen.add(k)
            lines.append(f"{k} = {v}")
        lines.append("")
    return "\n".join(lines)


def build() -> dict[str, str]:
    base_id = base_translations("Indonesian")
    en_stones, id_stones = stones_overrides(base_id)
    names = [(r["key"], r["id"]) for r in table("translations_id.csv")]
    pedia = [(r["en"], r["id"]) for r in table("civilopedia.csv")]
    return {
        "Indonesian.properties": render([("Names, places, events (data/translations_id.csv)", names),
                                         ("Civilopedia (data/civilopedia.csv)", pedia),
                                         (f"Gold is displayed as {STONES_ID} (overrides base translations)", id_stones)]),
        "English.properties": render([(f"Gold is displayed as {STONES_EN} (overrides base strings)", en_stones)]),
    }


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 if jsons/translations is out of date")
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args(argv)
    files = build()
    stale = [n for n, text in files.items() if not (OUT / n).is_file() or (OUT / n).read_text(encoding="utf-8") != text]
    if args.check:
        if stale:
            print("[gen_translations] out of date, run tools/gen_translations.py: " + ", ".join(stale))
            return 1
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for n, text in files.items():
        (OUT / n).write_text(text, encoding="utf-8")
    if not args.quiet:
        print("[gen_translations] " + ", ".join(f"{n}: {t.count(' = ')} lines" for n, t in files.items()))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
